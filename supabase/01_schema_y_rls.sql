-- ============================================================
-- 19. CREAR PERFIL AUTOMÁTICAMENTE AL REGISTRAR USUARIO
-- EN SUPABASE AUTH
-- ============================================================

create or replace function public.crear_perfil_usuario()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    rol_graduado bigint;
begin

    select id
    into rol_graduado
    from public.roles
    where nombre = 'GRADUADO'
    limit 1;

    if rol_graduado is null then
        raise exception 'No existe el rol GRADUADO';
    end if;

    insert into public.perfiles
    (
        id,
        id_rol,
        nombres,
        apellidos,
        telefono
    )
    values
    (
        new.id,
        rol_graduado,
        coalesce(new.raw_user_meta_data->>'nombres', ''),
        coalesce(new.raw_user_meta_data->>'apellidos', ''),
        coalesce(new.raw_user_meta_data->>'telefono', null)
    );

    return new;

end;
$$;


create trigger trg_crear_perfil_usuario
after insert on auth.users
for each row
execute function public.crear_perfil_usuario();


-- ============================================================
-- 20. FUNCIÓN PARA AUDITORÍA
-- ============================================================

create or replace function public.registrar_auditoria()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    registro_id text;
    usuario_id uuid;
    descripcion_registro text;
begin

    usuario_id := auth.uid();

    if TG_OP = 'DELETE' then

        registro_id := coalesce(
            to_jsonb(old)->>'id',
            ''
        );

        descripcion_registro :=
            'Registro eliminado de la tabla ' || TG_TABLE_NAME;

    elsif TG_OP = 'INSERT' then

        registro_id := coalesce(
            to_jsonb(new)->>'id',
            ''
        );

        descripcion_registro :=
            'Registro creado en la tabla ' || TG_TABLE_NAME;

    else

        registro_id := coalesce(
            to_jsonb(new)->>'id',
            ''
        );

        descripcion_registro :=
            'Registro actualizado en la tabla ' || TG_TABLE_NAME;

    end if;


    insert into public.auditoria
    (
        id_usuario,
        accion,
        tabla_afectada,
        id_registro,
        descripcion
    )
    values
    (
        usuario_id,
        TG_OP,
        TG_TABLE_NAME,
        registro_id,
        descripcion_registro
    );


    if TG_OP = 'DELETE' then
        return old;
    else
        return new;
    end if;

end;
$$;


