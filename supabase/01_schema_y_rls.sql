-- ============================================================
-- 2. ROLES
-- ============================================================

create table public.roles (
    id bigint generated by default as identity primary key,

    nombre varchar(30) not null unique,

    descripcion varchar(200),

    created_at timestamptz not null default now()
);


-- ============================================================
-- 3. PERFILES / USUARIOS
-- Vinculados con auth.users de Supabase
-- ============================================================

create table public.perfiles (

    id uuid primary key
        references auth.users(id)
        on delete cascade,

    id_rol bigint not null
        references public.roles(id)
        on delete restrict,

    nombres varchar(100) not null,

    apellidos varchar(100) not null,

    telefono varchar(30),

    estado boolean not null default true,

    created_at timestamptz not null default now(),

    updated_at timestamptz not null default now()
);


-- ============================================================
-- 4. GRADUADOS
-- Información específica del graduado
-- ============================================================

create table public.graduados (

    id uuid primary key
        references public.perfiles(id)
        on delete cascade,

    ci varchar(30) unique,

    fecha_nacimiento date,

    año_ingreso integer,

    año_egreso integer,

    año_titulacion integer,

    modalidad_titulacion varchar(100),

    ciudad varchar(100),

    departamento varchar(100),

    direccion varchar(255),

    linkedin varchar(255),

    created_at timestamptz not null default now(),

    updated_at timestamptz not null default now(),

    constraint chk_año_ingreso
        check (
            año_ingreso is null
            or año_ingreso >= 1900
        ),

    constraint chk_año_egreso
        check (
            año_egreso is null
            or año_egreso >= 1900
        ),

    constraint chk_año_titulacion
        check (
            año_titulacion is null
            or año_titulacion >= 1900
        ),

    constraint chk_años_graduado
        check (
            (
                año_ingreso is null
                or año_egreso is null
                or año_egreso >= año_ingreso
            )
            and
            (
                año_egreso is null
                or año_titulacion is null
                or año_titulacion >= año_egreso
            )
        )
);


-- ============================================================
-- 5. ENCUESTAS
-- ============================================================

create table public.encuestas (

    id uuid primary key
        default gen_random_uuid(),

    titulo varchar(200) not null,

    descripcion text,

    fecha_inicio date,

    fecha_fin date,

    estado boolean not null default false,

    id_usuario_creador uuid
        references public.perfiles(id)
        on delete set null,

    created_at timestamptz not null default now(),

    updated_at timestamptz not null default now(),

    constraint chk_fechas_encuesta
        check (
            fecha_fin is null
            or fecha_inicio is null
            or fecha_fin >= fecha_inicio
        )
);


-- ============================================================
-- 6. PREGUNTAS
-- ============================================================

create table public.preguntas (

    id uuid primary key
        default gen_random_uuid(),

    id_encuesta uuid not null
        references public.encuestas(id)
        on delete cascade,

    pregunta text not null,

    tipo varchar(30) not null,

    obligatoria boolean not null default false,

    orden integer not null default 1,

    valor_minimo integer,

    valor_maximo integer,

    etiqueta_minimo varchar(100),

    etiqueta_maximo varchar(100),

    created_at timestamptz not null default now(),

    constraint chk_tipo_pregunta
        check (
            tipo in (
                'TEXTO',
                'TEXTAREA',
                'NUMERO',
                'RADIO',
                'CHECKBOX',
                'SELECT',
                'ESCALA',
                'FECHA'
            )
        ),

    constraint chk_orden_pregunta
        check (
            orden > 0
        ),

    constraint chk_escala
        check (
            tipo <> 'ESCALA'
            or (
                valor_minimo is not null
                and valor_maximo is not null
                and valor_maximo > valor_minimo
            )
        )
);


-- ============================================================
-- 7. OPCIONES DE PREGUNTAS
-- RADIO, CHECKBOX y SELECT
-- ============================================================

create table public.opciones_pregunta (

    id uuid primary key
        default gen_random_uuid(),

    id_pregunta uuid not null
        references public.preguntas(id)
        on delete cascade,

    opcion varchar(255) not null,

    orden integer not null default 1,

    created_at timestamptz not null default now(),

    constraint chk_orden_opcion
        check (
            orden > 0
        )
);


-- ============================================================
-- 8. RESPUESTAS DE UNA ENCUESTA
-- Representa el envío completo de una encuesta
-- ============================================================

create table public.respuestas_encuesta (

    id uuid primary key
        default gen_random_uuid(),

    id_encuesta uuid not null
        references public.encuestas(id)
        on delete cascade,

    id_graduado uuid not null
        references public.graduados(id)
        on delete cascade,

    fecha_respuesta timestamptz not null default now(),

    estado varchar(20) not null default 'BORRADOR',

    created_at timestamptz not null default now(),

    updated_at timestamptz not null default now(),

    constraint chk_estado_respuesta
        check (
            estado in (
                'BORRADOR',
                'COMPLETADA'
            )
        ),

    constraint uq_graduado_encuesta
        unique (
            id_encuesta,
            id_graduado
        )
);


-- ============================================================
-- 9. RESPUESTAS DETALLADAS
-- ============================================================

create table public.respuestas (

