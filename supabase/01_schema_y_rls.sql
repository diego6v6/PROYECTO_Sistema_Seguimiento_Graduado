-- ============================================================
-- 22. VALIDAR QUE UNA RESPUESTA PERTENEZCA
-- A LA ENCUESTA CORRECTA
-- ============================================================

create or replace function public.validar_respuesta_pregunta()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare

    encuesta_respuesta uuid;

    encuesta_pregunta uuid;

    estado_respuesta varchar(20);

begin

    select
        re.id_encuesta,
        re.estado
    into
        encuesta_respuesta,
        estado_respuesta
    from public.respuestas_encuesta re
    where re.id = new.id_respuesta_encuesta;


    if encuesta_respuesta is null then

        raise exception
            'La respuesta de encuesta no existe';

    end if;


    select
        p.id_encuesta
    into
        encuesta_pregunta
    from public.preguntas p
    where p.id = new.id_pregunta;


    if encuesta_pregunta is null then

        raise exception
            'La pregunta no existe';

    end if;


    if encuesta_respuesta <> encuesta_pregunta then

        raise exception
            'La pregunta no pertenece a la encuesta respondida';

    end if;


    if estado_respuesta = 'COMPLETADA' then

        raise exception
            'No se puede modificar una encuesta completada';

    end if;


    return new;

end;
$$;


create trigger trg_validar_respuesta_pregunta
before insert or update on public.respuestas
for each row
execute function public.validar_respuesta_pregunta();


-- ============================================================
-- 23. VALIDAR OPCIÓN DE RESPUESTA
-- ============================================================

create or replace function public.validar_respuesta_opcion()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare

    pregunta_respuesta uuid;

    pregunta_opcion uuid;

    estado_respuesta varchar(20);

begin

    select
        r.id_pregunta,
        re.estado
    into
        pregunta_respuesta,
        estado_respuesta
    from public.respuestas r
    inner join public.respuestas_encuesta re
        on re.id = r.id_respuesta_encuesta
    where r.id = new.id_respuesta;


    if pregunta_respuesta is null then

        raise exception
            'La respuesta no existe';

    end if;


    select
        op.id_pregunta
    into
        pregunta_opcion
    from public.opciones_pregunta op
    where op.id = new.id_opcion;


    if pregunta_opcion is null then

        raise exception
            'La opción no existe';

    end if;


    if pregunta_respuesta <> pregunta_opcion then

        raise exception
            'La opción no pertenece a la pregunta';

    end if;


    if estado_respuesta = 'COMPLETADA' then

        raise exception
            'No se puede modificar una encuesta completada';

    end if;


    return new;

end;
$$;


create trigger trg_validar_respuesta_opcion
before insert or update on public.respuestas_opciones
for each row
execute function public.validar_respuesta_opcion();


-- ============================================================
-- 24. VALIDAR COMPLETADO DE ENCUESTA
-- Verifica que todas las preguntas obligatorias tengan respuesta
-- ============================================================

create or replace function public.validar_encuesta_completada()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare

    preguntas_obligatorias integer;

    preguntas_respondidas integer;

begin

    if new.estado = 'COMPLETADA'
       and (
           old.estado is distinct from 'COMPLETADA'
       ) then

        select count(*)
        into preguntas_obligatorias
        from public.preguntas p
        where p.id_encuesta = new.id_encuesta
          and p.obligatoria = true;


        select count(distinct r.id_pregunta)
        into preguntas_respondidas
        from public.respuestas r
        inner join public.preguntas p
            on p.id = r.id_pregunta
        where r.id_respuesta_encuesta = new.id
          and p.obligatoria = true;


        if preguntas_respondidas < preguntas_obligatorias then

            raise exception
                'No se puede completar la encuesta porque faltan preguntas obligatorias';

        end if;

        new.fecha_respuesta = now();

    end if;


    return new;

end;
$$;


create trigger trg_validar_encuesta_completada
before update on public.respuestas_encuesta
for each row
execute function public.validar_encuesta_completada();


