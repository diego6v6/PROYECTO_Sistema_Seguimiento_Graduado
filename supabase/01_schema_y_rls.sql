create or replace function public.obtener_rol_usuario()
returns text
language sql
security definer
stable
set search_path = public
as $$
    select r.nombre
    from public.perfiles p
    inner join public.roles r
        on r.id = p.id_rol
    where p.id = auth.uid()
    limit 1;
$$;


